export function translatePolicy(lang: Lang, field: PolicyField, value: string): string {
  const map = policyMaps[lang];
  if (map && map[value] && map[value][field]) return map[value][field]!;
  if (field === 'title') {
    const catMap = categoryMaps[lang] ?? {};
    if (catMap[value]) return catMap[value];
  }
  return value;
}

